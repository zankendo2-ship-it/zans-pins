#!/usr/bin/env python3
"""Close a correction gate. Run only by the 'ZANS correction receipt' workflow (allowlisted actor, main branch).
Posts a bot-authored receipt tied to the exact run, correction id and one applied/rejected decision per fix.
Refuses unknown, mismatched, duplicate or already-closed corrections. No paid call, no provider key."""
import os
import re
import sys

import orchestrator.orchestrate as o

DECISION_RE = re.compile(r"^\s*(\d+)\s*[=:]\s*(applied|rejected)\b\s*(.*)$", re.I)
HEX40 = re.compile(r"[0-9a-f]{40}")


def commit_exists(env, repo, sha):
    try:
        return o.gh(env, "GET", f"repos/{repo}/commits/{sha}").get("sha", "").startswith(sha)
    except Exception:   # noqa: BLE001
        return False


def fix_evidence_ok(env, repo, sha, path, digest):
    """Bound proof for one applied fix: the commit exists in this repo, that commit changed exactly this path, and the
    file's bytes at that commit hash to the stated sha256. An unrelated commit, a wrong path or a wrong hash fails."""
    import base64
    import hashlib
    try:
        c = o.gh(env, "GET", f"repos/{repo}/commits/{sha}")
        if not c.get("sha", "").startswith(sha) or path not in {f.get("filename") for f in c.get("files", [])}:
            return False
        f = o.gh(env, "GET", f"repos/{repo}/contents/{path}?ref={sha}")
        return f.get("encoding") == "base64" and hashlib.sha256(base64.b64decode(f.get("content", ""))).hexdigest() == digest
    except Exception:   # noqa: BLE001
        return False


PATH_RE = re.compile(r"[A-Za-z0-9._/-]{1,200}")


def build(env, comments, run, cid, decisions, verify=None):
    """One decision per listed fix, numbered 1..N exactly once. 'applied' needs the 40-hex commit that made the change
    and that commit must exist in this repo; 'rejected' needs a reason of at least 10 characters."""
    if not o.SHA64_RE.fullmatch(run) or not o.SHA64_RE.fullmatch(cid):
        raise o.Stop("REFUSED: run and correction must each be a full 64-hex id.")
    if (run, cid) not in o.pending_corrections(comments):
        raise o.Stop("REFUSED: no open correction gate with this exact run + correction id (wrong ids, already closed, or none).")
    expected = o.gate_count(comments, run, cid)
    if not expected:
        raise o.Stop("REFUSED: the gate does not state how many fixes it lists.")
    lines = [x for x in (decisions or "").replace(";", "\n").splitlines() if x.strip()]
    parsed = [DECISION_RE.match(x) for x in lines]
    if not lines or not all(parsed):
        raise o.Stop("REFUSED: give one 'N=applied <commit> <path> <sha256>' or 'N=rejected <reason>' decision per fix.")
    indices = [int(m.group(1)) for m in parsed]
    if sorted(indices) != list(range(1, expected + 1)):
        raise o.Stop(f"REFUSED: need exactly one decision for each of the {expected} fixes, numbered 1 to {expected} once each.")
    verify = verify or (lambda sha, path, digest: fix_evidence_ok(env, env.get("GITHUB_REPOSITORY", ""), sha, path, digest))
    for m in parsed:
        kind, rest = m.group(2).lower(), m.group(3).strip()
        if kind == "applied":
            parts = rest.split()
            ok = len(parts) == 3 and HEX40.fullmatch(parts[0].lower()) and PATH_RE.fullmatch(parts[1]) \
                and ".." not in parts[1] and o.SHA64_RE.fullmatch(parts[2].lower())
            if not ok:
                raise o.Stop(f"REFUSED: fix {m.group(1)} must be 'N=applied <40-hex commit> <changed path> <64-hex sha256 of that file at the commit>'.")
            key = (parts[0].lower(), parts[1], parts[2].lower())
            if not verify(*key):
                raise o.Stop(f"REFUSED: fix {m.group(1)} proof failed: the commit must exist here, change that path, and the file must hash to the stated sha256.")
            continue
        rest = rest.lower()
        if kind == "rejected" and len(rest) < 10:
            raise o.Stop(f"REFUSED: fix {m.group(1)} is 'rejected' without a reason of at least 10 characters.")
    applied = any(m.group(2).lower() == "applied" for m in parsed)
    head = (f"**Fix receipt (gate stays OPEN until the corrected artifact passes an independent re-review)** for run `{run}`, "
            f"correction `{cid}`: {len(lines)} decisions recorded." if applied else
            f"**Correction receipt** for run `{run}`, correction `{cid}`: {len(lines)} decisions recorded; nothing was changed, gate closed.")
    marker = o.FIXED if applied else o.RECEIPT
    body = "\n".join([head,
                      *[f"- {x.strip()}" for x in sorted(lines, key=lambda x: int(DECISION_RE.match(x).group(1)))],
                      f"<!-- {marker}:{run}:{cid} -->", "", "---", "_Generated by [Claude Code](https://claude.ai/code)_"])
    return body


def main(env=None):
    env = dict(os.environ if env is None else env)
    repo, issue = env.get("GITHUB_REPOSITORY", ""), env.get("ORCH_ISSUE", "").strip()
    try:
        allowed = {a.strip().lower() for a in env.get("ZANS_ORCH_ALLOWED_ACTORS", "").split(",") if a.strip()}
        if env.get("GITHUB_ACTOR", "").strip().lower() not in allowed or env.get("GITHUB_REF", "") != o.MAIN_REF:
            raise o.Stop("REFUSED: actor is not allowlisted or the run is not on main.")
        if issue != o.ALLOWED_ISSUE:
            raise o.Stop(f"REFUSED: only issue #{o.ALLOWED_ISSUE}.")
        comments = o.comments_since(env, repo, issue, "2026-01-01T00:00:00Z")
        body = build(env, comments, env.get("ORCH_RUN", "").strip().lower(), env.get("ORCH_CORRECTION", "").strip().lower(),
                     env.get("ORCH_DECISIONS", ""))
        o.gh(env, "POST", f"repos/{repo}/issues/{issue}/comments", {"body": body})
        print("receipt posted")
        return 0
    except o.Stop as s:
        print(str(s))
        return 1


if __name__ == "__main__":
    sys.exit(main())
